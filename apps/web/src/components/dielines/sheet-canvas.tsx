"use client";

import { useCallback, useEffect, useLayoutEffect, useRef, useState } from "react";
import { AppWindow, Hand, Maximize, Minus, Plus, SlidersHorizontal } from "lucide-react";
import type { WatermarkStyle } from "@/lib/watermark-settings";
import { DEFAULT_WATERMARK, SheetWatermark } from "./sheet-watermark";

export type ViewToggles = {
  bleed: boolean;
  safe: boolean;
  glue: boolean;
  dimensions: boolean;
  /** Each part's width x height written in the part. */
  partSizes: boolean;
  labels: boolean;
  /** Imported dielines: ignored lines the admin kept as a faint picture. */
  reference: boolean;
};

/** A named on/off switch in the canvas toolbar. */
export interface ToggleDef<K extends string = string> {
  key: K;
  label: string;
}

/** Toggles of the parametric dieline workspace. */
export const DIELINE_TOGGLES: ToggleDef<keyof ViewToggles>[] = [
  { key: "partSizes", label: "Dimensions" },
  { key: "dimensions", label: "Sheet size" },
  { key: "bleed", label: "Bleed" },
  { key: "safe", label: "Safe area" },
  { key: "glue", label: "Glue" },
  { key: "labels", label: "Panels" },
];

interface View {
  /** Pixels per millimetre. */
  k: number;
  x: number;
  y: number;
}

const MIN_K = 0.2;
const MAX_K = 40;

/** Flat dieline on a pannable, zoomable sheet. The SVG itself is generated by render-svg. */
export function SheetCanvas<T extends Record<string, boolean>>({
  bounds,
  src,
  toggles,
  toggleDefs,
  onToggles,
  legend,
  watermark = DEFAULT_WATERMARK,
  watermarkStyle,
  watermarkClip,
  onWindows,
  windowCount = 0,
  onHoverMm,
  highlight = null,
  onReady,
}: {
  /** Size (mm) of the picture `src` shows, margins included. */
  bounds: { width: number; height: number; minX?: number; minY?: number };
  src: string;
  toggles: T;
  toggleDefs: ToggleDef<Extract<keyof T, string>>[];
  onToggles: (t: T) => void;
  legend: { label: string; color: string; dashed?: boolean }[];
  /** Text tiled faintly behind the dieline; an empty string turns it off. */
  watermark?: string;
  /** Colours, letter size and line thickness of the watermark; the default look when absent. */
  watermarkStyle?: WatermarkStyle;
  /** Path data (sheet mm) that limits the watermark to the cut outline. */
  watermarkClip?: string;
  /** Opens the window editor (a button in the tool bar); absent = no such button. */
  onWindows?: () => void;
  /** How many windows there are, shown on that button. */
  windowCount?: number;
  /** Called with the sheet point (mm) under the mouse, and null when it leaves or a drag starts; absent = not tracked. */
  onHoverMm?: (p: { x: number; y: number } | null) => void;
  /** A panel outline (sheet mm) drawn softly over the sheet, e.g. the panel that blinks on the 3D box. */
  highlight?: readonly { x: number; y: number }[] | null;
  /** Called once, when the sheet picture is loaded and placed (so a loading placeholder can go away). */
  onReady?: () => void;
}) {
  const box = useRef<HTMLDivElement>(null);
  const readyOnce = useRef(false);
  const settling = useRef(false);
  /** The picture is loaded, decoded and has had two frames to be painted: only then is the sheet really there. */
  const settle = (img: HTMLImageElement) => {
    if (readyOnce.current || settling.current) return;
    settling.current = true;
    const done = () =>
      requestAnimationFrame(() =>
        requestAnimationFrame(() => {
          readyOnce.current = true;
          onReady?.();
        }),
      );
    if (typeof img.decode === "function") img.decode().then(done, done);
    else done();
  };
  const [view, setView] = useState<View | null>(null);
  const drag = useRef<{ id: number; x: number; y: number; vx: number; vy: number } | null>(null);
  const vb = bounds;

  const fit = useCallback(() => {
    const el = box.current;
    if (!el) return;
    const w = el.clientWidth;
    const h = el.clientHeight;
    const k = Math.min(w / vb.width, h / vb.height) * 0.92;
    setView({ k, x: (w - vb.width * k) / 2, y: (h - vb.height * k) / 2 });
  }, [vb.width, vb.height]);

  // Fit once the container has a size; later edits keep the user's pan and zoom (Fit button resets).
  useLayoutEffect(() => {
    if (!view) fit();
  }, [view, fit]);

  const zoomAt = useCallback((factor: number, cx: number, cy: number) => {
    setView((v) => {
      if (!v) return v;
      const k = Math.min(MAX_K, Math.max(MIN_K, v.k * factor));
      const f = k / v.k;
      return { k, x: cx - (cx - v.x) * f, y: cy - (cy - v.y) * f };
    });
  }, []);

  const zoomCentre = (factor: number) => {
    const el = box.current;
    if (el) zoomAt(factor, el.clientWidth / 2, el.clientHeight / 2);
  };

  // Wheel needs a non-passive listener so the page does not scroll while zooming.
  useEffect(() => {
    const el = box.current;
    if (!el) return;
    const onWheel = (e: WheelEvent) => {
      e.preventDefault();
      const r = el.getBoundingClientRect();
      zoomAt(Math.exp(-e.deltaY * 0.0015), e.clientX - r.left, e.clientY - r.top);
    };
    el.addEventListener("wheel", onWheel, { passive: false });
    return () => el.removeEventListener("wheel", onWheel);
  }, [zoomAt]);

  const onKey = (e: React.KeyboardEvent) => {
    const step = 40;
    const pan = (dx: number, dy: number) => setView((v) => (v ? { ...v, x: v.x + dx, y: v.y + dy } : v));
    if (e.key === "+" || e.key === "=") zoomCentre(1.25);
    else if (e.key === "-") zoomCentre(0.8);
    else if (e.key === "0") fit();
    else if (e.key === "ArrowLeft") pan(step, 0);
    else if (e.key === "ArrowRight") pan(-step, 0);
    else if (e.key === "ArrowUp") pan(0, step);
    else if (e.key === "ArrowDown") pan(0, -step);
    else return;
    e.preventDefault();
  };

  // The view options sit in a small popup (one button in the toolbar) instead of a row of buttons.
  const [menuOpen, setMenuOpen] = useState(false);
  const menuRef = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!menuOpen) return;
    const away = (e: PointerEvent) => {
      if (!menuRef.current?.contains(e.target as Node)) setMenuOpen(false);
    };
    const esc = (e: KeyboardEvent) => {
      if (e.key !== "Escape") return;
      e.stopPropagation();
      setMenuOpen(false);
    };
    document.addEventListener("pointerdown", away);
    document.addEventListener("keydown", esc, true);
    return () => {
      document.removeEventListener("pointerdown", away);
      document.removeEventListener("keydown", esc, true);
    };
  }, [menuOpen]);

  const toggle = (key: Extract<keyof T, string>, label: string) => (
    <button
      key={key}
      type="button"
      role="switch"
      aria-checked={toggles[key]}
      onClick={() => onToggles({ ...toggles, [key]: !toggles[key] })}
      className="flex w-full items-center gap-2.5 rounded-md px-2 py-1.5 text-left text-xs hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none"
    >
      <span className={`relative h-4 w-7 shrink-0 rounded-full transition-colors ${toggles[key] ? "bg-primary" : "bg-muted-foreground/30"}`} aria-hidden>
        <span className={`absolute top-0.5 size-3 rounded-full bg-background shadow transition-[left] ${toggles[key] ? "left-[0.8125rem]" : "left-0.5"}`} />
      </span>
      <span className="whitespace-nowrap">{label}</span>
    </button>
  );

  return (
    <div className="relative min-h-0 flex-1 overflow-hidden bg-muted/50">
      <div
        ref={box}
        role="application"
        aria-label="Dieline sheet. Drag to pan, scroll to zoom, arrow keys to move, plus and minus to zoom, 0 to fit."
        tabIndex={0}
        onKeyDown={onKey}
        onPointerDown={(e) => {
          if (e.button !== 0 || !view) return;
          e.currentTarget.setPointerCapture(e.pointerId);
          drag.current = { id: e.pointerId, x: e.clientX, y: e.clientY, vx: view.x, vy: view.y };
          onHoverMm?.(null);
        }}
        onPointerMove={(e) => {
          const d = drag.current;
          if (!d && onHoverMm && view) {
            const r = e.currentTarget.getBoundingClientRect();
            onHoverMm({ x: (e.clientX - r.left - view.x) / view.k + (vb.minX ?? 0), y: (e.clientY - r.top - view.y) / view.k + (vb.minY ?? 0) });
          }
          if (!d || d.id !== e.pointerId) return;
          setView((v) => (v ? { ...v, x: d.vx + e.clientX - d.x, y: d.vy + e.clientY - d.y } : v));
        }}
        onPointerUp={() => (drag.current = null)}
        onPointerCancel={() => (drag.current = null)}
        onPointerLeave={() => onHoverMm?.(null)}
        className="absolute inset-0 cursor-grab touch-none outline-none focus-visible:ring-2 focus-visible:ring-ring active:cursor-grabbing"
      >
        {view ? (
          <div
            className="pointer-events-none absolute left-0 top-0 select-none overflow-hidden rounded-sm bg-white shadow-sm"
            style={{ width: vb.width * view.k, height: vb.height * view.k, transform: `translate(${view.x}px, ${view.y}px)` }}
          >
            {/* eslint-disable-next-line @next/next/no-img-element -- generated SVG data URL */}
            <img ref={(el) => { if (el?.complete) settle(el); }} onLoad={(e) => settle(e.currentTarget)} src={src} alt="Flat dieline" draggable={false} className="absolute inset-0 size-full max-w-none" />
            {/* Above the picture: its SVG paints an opaque white sheet, which would hide a watermark under it. */}
            {highlight && highlight.length >= 3 ? (
              <svg aria-hidden className="absolute inset-0 size-full" viewBox={`${vb.minX ?? 0} ${vb.minY ?? 0} ${vb.width} ${vb.height}`}>
                <polygon points={highlight.map((q) => `${q.x},${q.y}`).join(" ")} fill="#2f6bff" fillOpacity={0.2} stroke="#2f6bff" strokeWidth={2 / (view?.k || 1)} strokeLinejoin="round" className="hover-pulse" />
              </svg>
            ) : null}
            <SheetWatermark bounds={vb} text={watermark} {...(watermarkStyle ? { style: watermarkStyle } : {})} {...(watermarkClip ? { clip: watermarkClip } : {})} />
          </div>
        ) : null}
      </div>

      <ul className="pointer-events-none absolute left-4 top-4 flex flex-col gap-1.5 text-xs" aria-label="Legend">
        {legend.map((l) => (
          <li key={l.label} className="flex items-center gap-2">
            <svg width="28" height="4" aria-hidden>
              <line x1="0" y1="2" x2="28" y2="2" stroke={l.color} strokeWidth="2" strokeDasharray={l.dashed ? "5 3" : undefined} />
            </svg>
            {l.label}
          </li>
        ))}
      </ul>

      <div
        role="toolbar"
        aria-label="Canvas tools"
        className="absolute bottom-4 left-1/2 flex -translate-x-1/2 items-center gap-1 rounded-xl border bg-background p-1 shadow-md"
      >
        <Tip label="Drag the sheet to pan">
          <span className="flex size-8 items-center justify-center text-muted-foreground">
            <Hand className="size-4" aria-hidden />
          </span>
        </Tip>
        <Tip label="Zoom in">
          <button type="button" aria-label="Zoom in" className="flex size-8 items-center justify-center rounded-md hover:bg-muted" onClick={() => zoomCentre(1.25)}>
            <Plus className="size-4" />
          </button>
        </Tip>
        <Tip label="Zoom out">
          <button type="button" aria-label="Zoom out" className="flex size-8 items-center justify-center rounded-md hover:bg-muted" onClick={() => zoomCentre(0.8)}>
            <Minus className="size-4" />
          </button>
        </Tip>
        <Tip label="Fit to screen">
          <button type="button" aria-label="Fit sheet to screen" className="flex size-8 items-center justify-center rounded-md hover:bg-muted" onClick={fit}>
            <Maximize className="size-4" />
          </button>
        </Tip>
        <span className="mx-1 h-5 w-px bg-border" aria-hidden />
        {onWindows ? (
          <Tip label="Window holes">
            <button type="button" aria-label="Window holes" onClick={onWindows} className="relative flex size-8 items-center justify-center rounded-md hover:bg-muted">
              <AppWindow className="size-4" />
              {windowCount > 0 ? <span className="absolute -top-1 -right-1 grid min-w-4 place-items-center rounded-full bg-primary px-1 text-[10px] leading-4 font-semibold text-primary-foreground">{windowCount}</span> : null}
            </button>
          </Tip>
        ) : null}
        <div ref={menuRef} className="relative">
          <Tip label="View options" hidden={menuOpen}>
          <button
            type="button"
            aria-label="View options"
            aria-haspopup="true"
            aria-expanded={menuOpen}
            onClick={() => setMenuOpen((o) => !o)}
            className={`flex size-8 items-center justify-center rounded-md hover:bg-muted ${menuOpen ? "bg-muted" : ""}`}
          >
            <SlidersHorizontal className="size-4" />
          </button>
          </Tip>
          {menuOpen ? (
            <div role="group" aria-label="View options" className="absolute bottom-full left-1/2 z-20 mb-3 flex w-44 -translate-x-1/2 flex-col rounded-xl border bg-background p-1 shadow-lg">
              {toggleDefs.map((d) => toggle(d.key, d.label))}
            </div>
          ) : null}
        </div>
      </div>
    </div>
  );
}

/** Tooltip centred above its child. Native `title` tips follow the cursor, so they never sit over the icon. */
function Tip({ label, hidden = false, children }: { label: string; hidden?: boolean; children: React.ReactNode }) {
  return (
    <span className="group/tip relative flex">
      {children}
      {hidden ? null : (
        <span
          role="tooltip"
          className="pointer-events-none absolute bottom-full left-1/2 z-30 mb-2 -translate-x-1/2 whitespace-nowrap rounded-md bg-foreground px-2.5 py-1 text-xs font-medium text-background opacity-0 shadow-md transition-opacity group-hover/tip:opacity-100 group-has-[:focus-visible]/tip:opacity-100"
        >
          {label}
          <span aria-hidden className="absolute -bottom-1 left-1/2 size-2 -translate-x-1/2 rotate-45 rounded-[1px] bg-foreground" />
        </span>
      )}
    </span>
  );
}
